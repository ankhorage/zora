import { createHash } from 'node:crypto';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

type RunCommand = (
  command: readonly string[],
  cwd: string,
  environment?: Readonly<Record<string, string>>,
) => void;

/*** Install the exact candidate provider where Ankh resolves provider packages. */
export function prepareCandidateProviderCache(
  providerCacheRoot: string,
  candidatePath: string,
  run: RunCommand,
): void {
  const providerPackageRoot = join(providerCacheRoot, 'providers');
  mkdirSync(providerPackageRoot, { recursive: true });
  writeFileSync(
    join(providerPackageRoot, 'package.json'),
    `${JSON.stringify({ name: 'zora-candidate-provider-cache', private: true }, null, 2)}\n`,
  );
  run(
    [
      'bun',
      'add',
      '--exact',
      '--omit=peer',
      '--silent',
      '--no-progress',
      '--no-summary',
      `@ankhorage/zora@file:${candidatePath}`,
    ],
    providerPackageRoot,
  );
}

/*** Verify that Ankh copied the installed candidate Reader byte-for-byte apart from its ownership header. */
export function verifyMaterializedReaderArtifact(
  fixtureRoot: string,
  candidateVersion: string,
): void {
  const installedReader = readFileSync(
    join(
      fixtureRoot,
      'node_modules',
      '@ankhorage',
      'zora',
      'web-dist',
      'components',
      'reader',
      'Reader.js',
    ),
    'utf8',
  );
  const materializedReader = readFileSync(
    join(fixtureRoot, '.ankh', 'zora', 'web', 'components', 'reader', 'Reader.js'),
    'utf8',
  );
  const header = `// Generated by @ankhorage/zora v${candidateVersion}. Do not edit manually.\n`;
  assert(
    materializedReader.startsWith(header),
    'Materialized Reader does not identify the packed ZORA candidate owner.',
  );
  assert(
    sha256(installedReader) === sha256(materializedReader.slice(header.length)),
    'Ankh materialized Reader content differs from the installed ZORA candidate.',
  );
  assert(
    /from ['"]@ankhorage\/reader['"]/u.test(materializedReader),
    'Materialized Reader does not preserve the external Reader import.',
  );
  assert(
    !materializedReader.includes('pdfjs-dist'),
    'Materialized Reader unexpectedly bundles PDF.js.',
  );
  const evidence = JSON.parse(
    readFileSync(join(fixtureRoot, '.ankh', 'zora', 'web', 'materialization.json'), 'utf8'),
  ) as { readonly owner: unknown; readonly ownerVersion: unknown };
  assert(evidence.owner === '@ankhorage/zora', 'Reader materialization has the wrong owner.');
  assert(
    evidence.ownerVersion === candidateVersion,
    'Reader materialization does not identify the packed candidate version.',
  );
}

/*** Produce stable artifact evidence without relying on filesystem metadata. */
function sha256(source: string): string {
  return createHash('sha256').update(source).digest('hex');
}

/*** Stop the candidate gate with an explicit contract failure. */
function assert(condition: boolean, message: string): asserts condition {
  if (!condition) throw new Error(message);
}
